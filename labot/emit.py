"""Write a Plan as a stand-alone Python module (the 'run file')."""
import pprint
from datetime import date

from . import catalog


def _fmt(obj):
    return pprint.pformat(obj, width=110, sort_dicts=False)


def emit_python(plan) -> str:
    spec, s = plan.spec, plan.summary
    used = sorted({v["labware"] for v in plan.instances.values()})
    labware = {k: dict(description=catalog.get(k).description, kind=catalog.get(k).kind,
                       rows=catalog.get(k).rows, cols=catalog.get(k).cols,
                       footprint=catalog.get(k).footprint, max_ul=catalog.get(k).max_ul,
                       dead_ul=catalog.get(k).dead_ul, tip_cap_ul=catalog.get(k).tip_cap_ul)
               for k in used}
    steps = [dict(index=i, name=st.name, type=st.type, source=st.source, target=st.target,
                  mode=st.mode if st.type == "transfer" else None, volume_ul=st.volume_ul,
                  tip=st.tip, mix_cycles=st.mix_cycles, duration_s=st.duration_s)
             for i, st in enumerate(spec.steps)]
    instances = {k: dict(v) for k, v in plan.instances.items()}
    parts = [
        f'"""Generated by LABOT on {date.today().isoformat()} - process "{spec.name}".\n\n'
        f'{plan.channels}-channel run, {spec.samples_per_run} samples, {spec.runs_per_day} runs/day.\n'
        'Do not edit by hand: change the process spec and regenerate.\n\n'
        'Conventions: COMMANDS is the complete flat run. `wells` are per-channel (top to bottom);\n'
        'a single well with n_channels > 1 means all channels use that well (trough).\n'
        'Volumes are uL per channel/well. Slots: M1-M3 front, M4-M6 back, F1-F3 / B1-B3 narrow.\n"""',
        f"RUN_NAME = {spec.name!r}",
        f"PROCESS = {spec.process!r}",
        f"CHANNELS = {plan.channels}",
        f"SAMPLES_PER_RUN = {spec.samples_per_run}",
        f"RUNS_PER_DAY = {spec.runs_per_day}",
        f"HOURS_PER_DAY = {spec.hours_per_day}",
        f"TIP_TYPES_UL = {spec.tip_types}",
        f"EXCESS_UL = {spec.excess_ul}",
        "DECK_LAYOUT = " + _fmt(spec.deck.describe()),
        "LABWARE = " + _fmt(labware),
        "INSTANCES = " + _fmt(instances),
        "DECK = " + _fmt(plan.deck),
        "REAGENTS = " + _fmt(plan.reagents),
        "INITIAL_VOLUMES_UL = " + _fmt(plan.initial_volumes),
        "STEPS = " + _fmt(steps),
        "SUMMARY = " + _fmt(s),
        "WARNINGS = " + _fmt(plan.warnings),
        "COMMANDS = " + _fmt(plan.commands),
        '''def execute(driver):
    """Replay COMMANDS on `driver`: one method per command name
    (pick_up_tip, aspirate, dispense, mix, drop_tip, manual, pause, comment)."""
    for c in COMMANDS:
        kw = {k: v for k, v in c.items() if k != "cmd"}
        getattr(driver, c["cmd"])(**kw)
''',
    ]
    return "\n\n".join(parts) + "\n"
